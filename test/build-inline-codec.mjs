/**
 * build-inline-codec.mjs — regenerate the inlined reference encoder embedded in
 * docs/index.html from the upstream codec via esbuild.
 *
 * The browser converter encodes packs by calling the SAME reference codec the
 * Node tests and the analyzer use — one encoder, so the browser and the
 * reference producer agree on the wire (digest AND body). But the page must stay
 * a single self-contained file (Playwright asserts zero external requests), so we
 * esbuild the codec's `encodeAuto` into a minified IIFE and EMBED it between the
 * CODEC-INLINE-START / CODEC-INLINE-END markers inside the converter engine.
 *
 * Re-run after ANY codec change. The drift guard (conformance INLINE-DRIFT) runs
 * this with --check and fails if the embedded copy and a fresh build disagree, so
 * the inlined encoder can never silently fall out of sync with source.
 *
 * Run:  node test/build-inline-codec.mjs            (write)
 *       node test/build-inline-codec.mjs --check     (verify; exit 1 on drift)
 *
 * Requires the sibling factstack repo at ../claude/factstack and `npx esbuild`.
 */
import { spawnSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join, resolve } from 'node:path';

const __dirname = dirname(fileURLToPath(import.meta.url));
const FACTSTACK = resolve(__dirname, '..', '..', 'claude', 'factstack');
// The vendored encodeAuto producer profile (facts-pack-owned; imports the
// codec's tracked encode()). Both this IIFE and the test bundle build from it.
const ENTRY = join(__dirname, '_encode-auto.ts');
const HTML = join(__dirname, '..', 'docs', 'index.html');
const START = '/* CODEC-INLINE-START — generated by test/build-inline-codec.mjs; do not edit by hand */';
const END = '/* CODEC-INLINE-END */';

/** esbuild the codec's encodeAuto into a single minified IIFE exposing
 *  `__FPCODEC.encodeAuto`. The codec is dependency-free (pure-JS sha256), so the
 *  browser-platform build needs no externals or shims. */
function buildIife() {
  const cmd =
    `npx esbuild "${ENTRY}" --bundle --format=iife --global-name=__FPCODEC ` +
    `--minify --legal-comments=none --platform=browser`;
  const r = spawnSync(cmd, { cwd: FACTSTACK, encoding: 'utf8', shell: true });
  if (r.status !== 0) {
    process.stderr.write((r.stderr || 'esbuild failed') + '\n');
    process.exit(r.status ?? 1);
  }
  return r.stdout.trim();
}

/** Splice a fresh IIFE between the two markers, leaving everything else byte
 *  identical. Idempotent: same source ⇒ same embedded text. */
function embed(html, iife) {
  // Defensive: if the minified IIFE ever contained a marker substring (e.g. a
  // future codec string literal), indexOf would find the inner one first and
  // silently corrupt the splice. Fail loudly instead.
  if (iife.includes(START) || iife.includes(END)) {
    throw new Error('built IIFE contains a CODEC-INLINE marker substring — splice would corrupt; rename the marker');
  }
  const a = html.indexOf(START);
  const b = html.indexOf(END);
  if (a === -1 || b === -1 || b <= a) {
    throw new Error('CODEC-INLINE markers not found in docs/index.html');
  }
  return `${html.slice(0, a + START.length)}\n  ${iife}\n  ${html.slice(b)}`;
}

const check = process.argv.includes('--check');
const iife = buildIife();
const html = readFileSync(HTML, 'utf8');
const updated = embed(html, iife);

if (check) {
  if (html !== updated) {
    process.stderr.write(
      'INLINE DRIFT: docs/index.html embedded codec differs from a fresh build.\n' +
        'Run: node test/build-inline-codec.mjs\n',
    );
    process.exit(1);
  }
  console.log('inline codec is up to date with source');
  process.exit(0);
}
writeFileSync(HTML, updated);
console.log(`Embedded ${iife.length} B minified IIFE codec into docs/index.html`);
